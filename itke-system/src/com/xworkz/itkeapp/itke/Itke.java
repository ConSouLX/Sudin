package com.xworkz.itkeapp.itke;

public class Itke {

    private int itkeId;
    private String itkeType;
    private String itkeSize;
    private int itkeWeight;

    public void setItkeId(int itkeId){
        this.itkeId = itkeId;
    }
    public int getItkeId(){
        return itkeId;
    }
    public void setItkeType(String itkeType){
        this.itkeType = itkeType;
    }
    public String getItkeType(){
        return itkeType;
    }
    public void setItkeSize(String itkeSize){
        this.itkeSize = itkeSize;
    }
    public String getItkeSize(){
        return itkeSize;
    }
    public void setItkeWeight(int itkeWeight){
        this.itkeWeight = itkeWeight;
    }
    public int getItkeWeight(){
        return itkeWeight;
    }
}

