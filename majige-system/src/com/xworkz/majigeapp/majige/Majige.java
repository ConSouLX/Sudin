package com.xworkz.majigeapp.majige;

public class Majige {

    private int majigeId;
    private String majigeType;
    private String majigeSize;
    private int majigeVolume;

    public void setMajigeId(int majigeId){
        this.majigeId = majigeId;
    }
    public int getMajigeId(){
        return majigeId;
    }
    public void setMajigeType(String majigeType){
        this.majigeType = majigeType;
    }
    public String getMajigeType(){
        return majigeType;
    }
    public void setMajigeSize(String majigeSize){
        this.majigeSize = majigeSize;
    }
    public String getMajigeSize(){
        return majigeSize;
    }
    public void setMajigeVolume(int majigeVolume){
        this.majigeVolume = majigeVolume;
    }
    public int getMajigeVolume(){
        return majigeVolume;
    }
}

